"""Nothing under skills/ may carry the host repository's vocabulary.

This directory is written to be published on its own. The check is crude on
purpose: a substring scan over every text file, with no exceptions list, so
adding a term is a decision somebody has to make deliberately rather than a
line that slips through review.
"""

import unittest
from pathlib import Path

SKILLS_ROOT = Path(__file__).resolve().parents[2]

FORBIDDEN = (
    "pptx", "powerpoint", "slide", "deck", "roundtrip_fidelity", "roundtrip-fidelity",
    "roundtrip", "diff_mode_search", "inverse-demo", "slide-diff", "marvin", "widgetlabs",
    "slide-crafter", "slide_crafter",
)

# Run records, logs and generated pages are published too, and a file with no
# suffix -- `Dockerfile`, `gitignore`, a script -- is text as often as not.
SUFFIXES = {".md", ".py", ".sh", ".toml", ".txt", ".json", ".yaml", ".yml", ".jsonl", ".log", ".html", ""}
SKIP_DIRS = {".venv", "__pycache__", ".pytest_cache", "node_modules", ".git"}

# Directories not yet scrubbed, each with the reason it is still here. A directory
# listed here is publication debt: it cannot be published until it is removed.
DEFERRED: dict[str, str] = {}


def _is_derived_experiment_dir(rel_parts: tuple[str, ...]) -> bool:
    """`<experiment-root>/state` and `<experiment-root>/outputs`: gitignored
    run data, regenerated by running the experiment, never publication
    content. Matched by exact position (the third path component, directly
    under `examples/<name>/`) rather than by name anywhere in the path, so a
    *committed* directory that happens to share the name deeper in the tree —
    e.g. a viewer's checked-in `fixtures/state/` — is still scanned. Widening
    this to match `state`/`outputs` anywhere would silently exempt exactly
    the kind of committed fixture the scan exists to cover.
    """
    return len(rel_parts) >= 3 and rel_parts[0] == "examples" and rel_parts[2] in {"state", "outputs"}


class NoProprietaryTerms(unittest.TestCase):
    def test_no_proprietary_term_appears_under_skills(self):
        offenders = []
        for path in sorted(SKILLS_ROOT.rglob("*")):
            if not path.is_file() or path.suffix not in SUFFIXES:
                continue
            if any(part in SKIP_DIRS for part in path.parts):
                continue
            if _is_derived_experiment_dir(path.relative_to(SKILLS_ROOT).parts):
                continue
            if any(part in DEFERRED for part in path.parts):
                continue
            if path.resolve() == Path(__file__).resolve():
                continue
            lowered = path.read_text(encoding="utf-8", errors="replace").lower()
            for term in FORBIDDEN:
                if term in lowered:
                    offenders.append(f"{path.relative_to(SKILLS_ROOT)}: {term}")
        self.assertEqual(offenders, [], "\n".join(offenders))

    def test_every_deferred_directory_carries_a_reason(self):
        for name, reason in DEFERRED.items():
            self.assertTrue(reason.strip(), f"{name} is excluded with no reason")
            self.assertTrue((SKILLS_ROOT / name).is_dir(), f"{name} is excluded but does not exist")

    def test_nothing_is_deferred_silently(self):
        # A deferred directory must actually still be dirty. When one is
        # cleaned, this fails and the exclusion is removed rather than left to
        # rot as a permanent hole in the check.
        for name in DEFERRED:
            hits = []
            for path in sorted((SKILLS_ROOT / name).rglob("*")):
                if not path.is_file() or path.suffix not in SUFFIXES:
                    continue
                if any(part in SKIP_DIRS for part in path.parts):
                    continue
                if _is_derived_experiment_dir(path.relative_to(SKILLS_ROOT).parts):
                    continue
                lowered = path.read_text(encoding="utf-8", errors="replace").lower()
                hits += [term for term in FORBIDDEN if term in lowered]
            self.assertTrue(hits, f"{name} is clean now — remove it from DEFERRED")


if __name__ == "__main__":
    unittest.main()
